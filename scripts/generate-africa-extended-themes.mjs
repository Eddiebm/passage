const DISPLAY = {
  libre: "var(--font-libre-baskerville), Georgia, 'Times New Roman', serif",
  cormorant: 'var(--font-cormorant), Georgia, serif',
  dm: 'var(--font-dm-sans), system-ui, sans-serif',
}

function block(t) {
  const display = DISPLAY[t.display] ?? DISPLAY.libre
  const kente = t.kente
    ? `  --passage-kente-band: linear-gradient(90deg, #8b2028 0%, #1a5c38 50%, #d4a830 100%);`
    : '  --passage-kente-band: none;'

  return `html[data-theme='${t.id}'], .passage-memorial-root[data-theme='${t.id}'] {
  --background: ${t.bg};
  --foreground: ${t.text};
  --passage-bg: ${t.bg};
  --passage-surface: ${t.surface};
  --passage-card-bg: ${t.surface};
  --passage-text: ${t.text};
  --passage-muted: ${t.muted};
  --passage-heading: ${t.heading};
  --passage-accent: ${t.accent};
  --passage-rule: ${t.rule};
  --passage-link: ${t.link};
  --passage-hero-bg: ${t.heroBg};
  --passage-hero-text: ${t.heroText};
  --passage-hero-muted: ${t.heroMuted};
  --passage-header-bg: ${t.headerBg};
  --passage-header-text: ${t.headerText};
  --passage-header-link: ${t.headerLink};
  --passage-font-display: ${display};
  --passage-font-body: var(--font-dm-sans), system-ui, sans-serif;
  --passage-content-max: ${t.max};
  --passage-radius: ${t.radius};
  --passage-shadow: none;
${kente}
}
`
}

